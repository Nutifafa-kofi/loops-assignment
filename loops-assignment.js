// function to calculate sum of numbers from 1 to n (inclusive)
function sumNumbers(n) {
  let sum = 0; // declared a sum variable
  // loop to iterate through the numbers to calculate
  for (let i = 1; i <= n; i++) {
    sum += i; // add sum and each numbers together
  }
  return sum;
}

